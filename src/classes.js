const DOC_LINKS = DOC_PREFIXES.toSorted(
  (left, right) =>
    right[0].length - left[0].length || left[0].localeCompare(right[0]),
);

const classes = data.classes.map((entry, index) => ({
  detail: entry.detail,
  name: entry.name,
  sortText: String(index).padStart(4, "0"),
}));

const byName = new Map(classes.map((entry) => [entry.name, entry]));

function baseName(name) {
  const variant = VARIANTS.find((item) => name.startsWith(`${item}:`));

  return variant ? name.slice(variant.length + 1) : name;
}

function docsUrl(name) {
  const base = baseName(name);
  const match = DOC_LINKS.find(
    ([prefix]) => base === prefix || base.startsWith(prefix),
  );

  return `${DOCS_ROOT}${match?.[1] ?? ""}`;
}

function documentationForClass(entry) {
  const parts = [`**${entry.name}**`];

  if (entry.detail) {
    parts.push(`\`${entry.detail.replaceAll("`", "")}\``);
  }

  parts.push(translate("[Docs]({0})", docsUrl(entry.name)));

  return parts.join("\n\n");
}

function classByName(name) {
  return byName.get(name) ?? null;
}

